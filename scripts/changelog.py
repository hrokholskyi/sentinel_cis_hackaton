"""Monitored paths, rules/rules.lock and CHANGELOG.md, shared by infra_check and change_request.

CHANGELOG.md and rules/rules.lock are generated: only scripts/change_request.sh writes them.
A commit is COVERED when its short hash is listed in an entry of CHANGELOG.md.
"""

import hashlib
import re
import subprocess
from pathlib import Path
from typing import Optional

ROOT = Path(__file__).resolve().parent.parent
RULES = ROOT / "rules"
LOCK = RULES / "rules.lock"
CHANGELOG = ROOT / "CHANGELOG.md"
MONITORED = ["rules", "breaker", ".env.example", "requirements.txt"]
PATHSPECS = MONITORED + [":(exclude)rules/rules.lock"]
LOCK_HEADER = "# Generated by scripts/change_request.sh from rules/*.sql. Do not edit by hand."
CHANGELOG_HEADER = "<!-- Generated by scripts/change_request.sh. Do not edit by hand. -->"
_HASH = re.compile(r"\b[0-9a-f]{7,40}\b")


class GitError(RuntimeError):
    pass


def git(*args: str) -> str:
    try:
        r = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, timeout=60)
    except (OSError, subprocess.TimeoutExpired) as e:
        raise GitError(f"git {' '.join(args)}: {e}") from e
    if r.returncode != 0:
        raise GitError(f"git {' '.join(args)}: {r.stderr.strip()}")
    return r.stdout


def commits(since: Optional[str] = None) -> list[dict]:
    """Commits that touched monitored paths, oldest first: {hash, short, date, subject}."""
    args = ["log", "--reverse", "--format=%H%x09%h%x09%cI%x09%s"]
    if since:
        args.append(f"--since={since}")
    out = git(*args, "--", *PATHSPECS)
    rows = []
    for line in out.splitlines():
        full, short, date, subject = line.split("\t", 3)
        rows.append({"hash": full, "short": short, "date": date, "subject": subject})
    return rows


def uncommitted() -> list[str]:
    """Uncommitted changes (including untracked files) in monitored paths, as porcelain lines."""
    out = git("status", "--porcelain=v1", "--untracked-files=all", "--", *PATHSPECS)
    return [line for line in out.splitlines() if line.strip()]


def changelog_text() -> str:
    try:
        return CHANGELOG.read_text()
    except FileNotFoundError:
        return ""


def covered(full_hash: str, text: Optional[str] = None) -> bool:
    text = changelog_text() if text is None else text
    return any(full_hash.startswith(tok) for tok in _HASH.findall(text))


def rule_checksums() -> dict[str, str]:
    return {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(RULES.glob("*.sql"))}


def lock_text() -> str:
    lines = [LOCK_HEADER] + [f"{digest}  {name}" for name, digest in rule_checksums().items()]
    return "\n".join(lines) + "\n"


def read_lock() -> Optional[dict[str, str]]:
    try:
        text = LOCK.read_text()
    except FileNotFoundError:
        return None
    out = {}
    for line in text.splitlines():
        if line.strip() and not line.startswith("#"):
            digest, name = line.split(None, 1)
            out[name.strip()] = digest
    return out


def lock_diff() -> list[str]:
    """Differences between rules/*.sql and rules/rules.lock, one line each."""
    lock = read_lock()
    if lock is None:
        return ["rules/rules.lock is missing"]
    now = rule_checksums()
    diff = [f"changed: rules/{n}" for n in sorted(now) if n in lock and lock[n] != now[n]]
    diff += [f"missing: rules/{n} (in rules.lock, not on disk)" for n in sorted(lock) if n not in now]
    diff += [f"extra:   rules/{n} (on disk, not in rules.lock)" for n in sorted(now) if n not in lock]
    return diff
